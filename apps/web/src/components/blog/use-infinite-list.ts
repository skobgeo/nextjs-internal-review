import { useState } from 'react';

/**
 * [T-03] Хук бесконечной прокрутки.
 *
 * Лента статей (`article-feed.tsx`) уже вызывает его и ждёт от него:
 *  - `items`     — накопленный список (начинается с того, что отрендерил сервер);
 *  - `hasMore`   — есть ли ещё страницы (у нас известен `total` и `perPage`);
 *  - `isLoading` — идёт ли загрузка сейчас;
 *  - `error`     — текст последней ошибки или `null`;
 *  - `loadMore`  — загрузить следующую страницу через `options.fetchPage(page)`.
 *
 * Сейчас это заглушка: она возвращает стартовые элементы и никогда ничего
 * не догружает. Сигнатура написана «на потом» — на `any`.
 *
 * Задача:
 *  1. типизировать хук дженериком по типу элемента: лента статей — не единственный
 *     список на сайте, хук не должен знать про статьи;
 *  2. реализовать `loadMore` так, чтобы повторный вызов во время загрузки
 *     не запускал второй запрос, а ошибка не ломала уже показанный список;
 *  3. в `article-feed.tsx` вызывать `loadMore` автоматически, когда пользователь
 *     доскроллил до конца списка (IntersectionObserver), оставив кнопку как
 *     запасной вариант;
 *  4. подумать вслух: что должно произойти с накопленным списком, когда меняется
 *     поисковый запрос, и что будет с ответом, который пришёл уже после этого.
 */
export function useInfiniteList(options: any): any {
  const [items] = useState(options.initialItems);

  return {
    items,
    hasMore: false,
    isLoading: false,
    error: null,
    loadMore: () => {},
  };
}
