/**
 * [T-06] Throttle: `fn` вызывается не чаще одного раза в `intervalMs`.
 *
 * Им пользуется индикатор прогресса чтения на странице статьи
 * (`components/blog/reading-progress.tsx`): обработчик `scroll` дёргается
 * десятки раз в секунду, а перерисовывать полоску так часто незачем.
 *
 * Сейчас это заглушка: она просто вызывает `fn` — откройте статью, полистайте
 * и посмотрите в консоль. Заодно её сигнатура «на потом» написана на `any`.
 *
 * Что нужно:
 *  1. Семантика leading + trailing: первый вызов серии выполняется сразу,
 *     следующие — не чаще одного раза в `intervalMs`, при этом ПОСЛЕДНИЙ
 *     вызов серии не теряется (выполняется с его аргументами, когда интервал истечёт).
 *  2. Метод `cancel()` отменяет отложенный trailing-вызов.
 *  3. Строгая типизация: аргументы `fn` выводятся дженериком и сохраняются
 *     у возвращаемой функции — по образцу `DebouncedFunction` рядом.
 *
 * Тесты: `pnpm test:core`.
 */
export function throttle(fn: any, intervalMs: number): any {
  void intervalMs;

  const throttled = (...args: any[]) => {
    fn(...args);
  };

  throttled.cancel = () => {};

  return throttled;
}
